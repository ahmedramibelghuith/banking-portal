CREATE TABLE operation_request (
 id bigint generated by default as identity PRIMARY KEY, client_id bigint NOT NULL, request_key varchar(36) NOT NULL,
 fingerprint varchar(256) NOT NULL, operation_id bigint,
 CONSTRAINT uq_customer_request UNIQUE(client_id, request_key),
 CONSTRAINT fk_request_client FOREIGN KEY(client_id) REFERENCES clients(id),
 CONSTRAINT fk_request_operation FOREIGN KEY(operation_id) REFERENCES operation(id)
);
CREATE INDEX ix_operation_account_date ON operation(compte_id, date_operation, id);
